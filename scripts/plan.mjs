#!/usr/bin/env node
// Plan status tool. Single source of truth = frontmatter in tickets/*.md.
//
//   node scripts/plan.mjs          regenerate the status block in PLAN.md
//   node scripts/plan.mjs --next   print tickets that can be started now (the frontier)
//   node scripts/plan.mjs --check  exit 1 if PLAN.md is out of date
//
// No dependencies. Ticket frontmatter fields: id, title, status, blocked_by, model.
// status: todo | in-progress | needs-device | done
// "needs-device" = code complete, waiting for on-device check by the owner; it unblocks dependants.

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ticketDir = join(root, "tickets");
const planPath = join(root, "PLAN.md");
const START = "<!-- plan:start (generated by scripts/plan.mjs — do not edit by hand) -->";
const END = "<!-- plan:end -->";
const STATUSES = ["todo", "in-progress", "needs-device", "done"];

function parseFrontmatter(text, file) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n/);
  if (!m) throw new Error(`${file}: missing frontmatter`);
  const fm = {};
  for (const line of m[1].split("\n")) {
    const kv = line.match(/^(\w+):\s*(.*)$/);
    if (!kv) continue;
    let [, k, v] = kv;
    v = v.trim();
    if (v.startsWith("[")) {
      v = v.slice(1, -1).split(",").map((s) => s.trim().replace(/^["']|["']$/g, "")).filter(Boolean);
    } else {
      v = v.replace(/^["']|["']$/g, "");
    }
    fm[k] = v;
  }
  const body = text.slice(m[0].length);
  const done = (body.match(/^\s*- \[x\]/gim) || []).length;
  const open = (body.match(/^\s*- \[ \]/gm) || []).length;
  if (!STATUSES.includes(fm.status)) throw new Error(`${file}: bad status "${fm.status}"`);
  return { ...fm, file, done, total: done + open };
}

const tickets = readdirSync(ticketDir)
  .filter((f) => /^\d\d-.*\.md$/.test(f))
  .sort()
  .map((f) => parseFrontmatter(readFileSync(join(ticketDir, f), "utf8"), f));
const byId = Object.fromEntries(tickets.map((t) => [t.id, t]));
const isDone = (t) => t.status === "done" || t.status === "needs-device";

function state(t) {
  if (t.status !== "todo") return t.status;
  const missing = (t.blocked_by || []).filter((b) => !byId[b] || !isDone(byId[b]));
  return missing.length ? "blocked" : "ready";
}

const ICON = { done: "✅", "needs-device": "📱", "in-progress": "🚧", ready: "🟢", blocked: "⛔" };

function render() {
  const lines = [START, ""];
  const finished = tickets.filter(isDone).length;
  lines.push(`**Progress:** ${finished}/${tickets.length} tickets complete.`, "");
  lines.push("```mermaid", "flowchart LR");
  for (const t of tickets) lines.push(`  T${t.id}["${t.id} · ${t.title.replace(/"/g, "'")}"]:::${state(t).replace("-", "")}`);
  for (const t of tickets) for (const b of t.blocked_by || []) lines.push(`  T${b} --> T${t.id}`);
  lines.push(
    "  classDef done fill:#d4edda,stroke:#2e7d32,color:#000",
    "  classDef needsdevice fill:#e3f2fd,stroke:#1565c0,color:#000",
    "  classDef inprogress fill:#fff3cd,stroke:#b8860b,color:#000",
    "  classDef ready fill:#ffffff,stroke:#2e7d32,stroke-width:3px,color:#000",
    "  classDef blocked fill:#eeeeee,stroke:#999,color:#555",
    "```",
    "",
    "| | # | Ticket | Model | Blocked by | Criteria | State |",
    "|---|---|---|---|---|---|---|",
  );
  for (const t of tickets) {
    const s = state(t);
    const box = isDone(t) ? "[x]" : "[ ]";
    const blockers = (t.blocked_by || []).length ? t.blocked_by.join(", ") : "—";
    lines.push(`| ${box} | ${t.id} | [${t.title}](tickets/${t.file}) | ${t.model} | ${blockers} | ${t.done}/${t.total} | ${ICON[s]} ${s} |`);
  }
  lines.push("", "Legend: ✅ done · 📱 code done, waiting for on-device check · 🚧 in progress · 🟢 ready to start · ⛔ blocked", "", END);
  return lines.join("\n");
}

const plan = readFileSync(planPath, "utf8");
const re = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END}`);
if (!re.test(plan)) throw new Error("PLAN.md is missing the plan:start/plan:end markers");
const next = plan.replace(re, render());
const arg = process.argv[2];

if (arg === "--next") {
  const frontier = tickets.filter((t) => state(t) === "ready");
  const active = tickets.filter((t) => t.status === "in-progress");
  for (const t of active) console.log(`🚧 ${t.id} ${t.title}  (in progress)`);
  for (const t of frontier) console.log(`🟢 ${t.id} ${t.title}  [${t.model}]  tickets/${t.file}`);
  if (!frontier.length && !active.length) console.log("Nothing ready — all done or blocked.");
} else if (arg === "--check") {
  if (next !== plan) { console.error("PLAN.md is out of date — run: node scripts/plan.mjs"); process.exit(1); }
  console.log("PLAN.md is up to date.");
} else {
  writeFileSync(planPath, next);
  console.log("PLAN.md updated.");
}
